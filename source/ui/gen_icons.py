def render(rows):
    assert len(rows) == SIZE, "an icon has 16 rows"
    mask = []
    for row in rows:
        assert len(row) == SIZE and set(row) <= {"#", "."}, row
        mask += [255 if c == "#" else 0 for c in row]
    return mask


def sources():
    names = list(ICONS)
    header = [
        "/* Generated by gen_icons.py; do not edit. */",
        "#ifndef ICONS_DATA_H",
        "#define ICONS_DATA_H",
        "",
        f"#define ICON_MASK_SIZE {SIZE}",
        "",
        "typedef enum {",
        *[f"\tICON_{name}," for name in names],
        "\tICON_COUNT",
        "} icon_id;",
        "",
        "/* 0 or 255 per pixel, row by row from the top. */",
        "extern const unsigned char "
        "icon_masks[ICON_COUNT][ICON_MASK_SIZE * ICON_MASK_SIZE];",
        "",
        "#endif",
        "",
    ]
    body = [
        "/* Generated by gen_icons.py; do not edit. */",
        '#include "icons_data.h"',
        "",
        "const unsigned char "
        "icon_masks[ICON_COUNT][ICON_MASK_SIZE * ICON_MASK_SIZE] = {",
    ]
    for name in names:
        mask = render(ICONS[name])
        body.append(f"\t[ICON_{name}] = {{")
        for row in range(SIZE):
            values = mask[row * SIZE:(row + 1) * SIZE]
            body.append("\t\t" + ", ".join(f"{v:3d}" for v in values) + ",")
        body.append("\t},")
    body += ["};", ""]
    return "\n".join(body), "\n".join(header)


def is_current():
    c_text, h_text = sources()

    def read(path):
        return path.read_text(encoding="utf-8").replace("\r\n", "\n") \
            if path.exists() else None
    return read(OUT_C) == c_text and read(OUT_H) == h_text


def main(argv):
    if "--check" in argv:
        if is_current():
            return 0
        print("icons_data.[ch] are stale: run source/ui/gen_icons.py")
        return 1
    c_text, h_text = sources()
    OUT_C.write_text(c_text, encoding="utf-8", newline="\n")
    OUT_H.write_text(h_text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_C.name} and {OUT_H.name} ({len(ICONS)} icons)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
